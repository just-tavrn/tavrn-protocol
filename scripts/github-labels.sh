# Creates or updates the issue labels of this repository (idempotent).
# Usage: scripts/github-labels.sh [owner/repo]   (default: just-tavrn/tavrn-protocol; needs an authenticated `gh`)
set -euo pipefail
repo="${1:-just-tavrn/tavrn-protocol}"

label() { gh label create "$1" --repo "$repo" --color "$2" --description "$3" --force; }

label "bug"              "d73a4a" "An error, contradiction or ambiguity in the specification"
label "enhancement"      "a2eeef" "A proposal for a new feature or capability"
label "documentation"    "0075ca" "Wording, examples, structure; no normative change"
label "spec-change"      "5319e7" "Changes normative behaviour of nodes or clients"
label "breaking"         "b60205" "Not a compatible extension (needs /api/v2 or a new capability)"
label "capability"       "c5def5" "Adds or changes a capability string"
label "openapi"          "1d76db" "openapi.json (generated by the reference node)"
label "test-vectors"     "0e8a16" "testvectors/*.json"
label "permissions"      "fbca04" "Permission bits and their evaluation (permissions.md)"
label "federation"       "bfd4f2" "FEDERATION.md"
label "encryption"       "006b75" "ENCRYPTION.md (MLS, keys, backups)"
label "voice"            "f9d0c4" "VOICE.md and WHITEBOARD.md"
label "applications"     "d4c5f9" "APPLICATIONS.md (bots, commands, webhooks, SSO)"
label "security"         "ee0701" "Security relevant (report vulnerabilities privately, not in issues)"
label "question"         "d876e3" "Further information is requested"
label "good first issue" "7057ff" "Good for newcomers"
label "help wanted"      "008672" "Extra attention is needed"
label "dependencies"     "0366d6" "Dependency updates (Dependabot)"
label "github-actions"   "000000" "Workflow updates"
